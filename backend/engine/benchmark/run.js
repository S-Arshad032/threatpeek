function parseSet(argv) {
  const arg = argv.find((a) => a.startsWith("--set="));
  const name = arg ? arg.slice("--set=".length) : DEFAULT_SET;
  if (!SETS.includes(name)) {
    console.error(`Unknown set "${name}". Use --set=${SETS.join("|")}.`);
    process.exit(2);
  }
  return name;
}

function updateResults(name, section) {
  const start = `<!-- set:${name} -->`;
  const end = `<!-- /set:${name} -->`;
  const block = `${start}\n${section}\n${end}`;
  const sections = {};
  if (existsSync(RESULTS_FILE)) {
    const old = readFileSync(RESULTS_FILE, "utf8");
    for (const s of SETS) {
      const m = old.match(new RegExp(`<!-- set:${s} -->[\\s\\S]*?<!-- /set:${s} -->`));
      if (m) sections[s] = m[0];
    }
  }
  sections[name] = block;
  const body = SETS.filter((s) => sections[s]).map((s) => sections[s]).join("\n\n");
  writeFileSync(RESULTS_FILE, `${HEADER}\n\n${body}\n`);
}

const name = parseSet(process.argv.slice(2));
const messages = loadSet(name);
if (messages.length === 0) {
  console.log(`Benchmark set: ${name} is empty, nothing to score.`);
  const note = setNote(name);
  if (note) console.log(note);
  process.exit(0);
}
const ev = evaluate(messages);
console.log(formatText(name, ev));
updateResults(name, formatMarkdown(name, ev, new Date().toISOString().slice(0, 10)));
console.log(`\nWrote ${RESULTS_FILE}`);
