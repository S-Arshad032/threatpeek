// `npm run benchmark [-- --set=dev|heldout|heldout2|heldout3|heldout4]`: scores a benchmark set, prints a
// report and updates that set's section of benchmark/RESULTS.md (the other sets' sections are kept).
// An empty set (heldout4 today) prints its note and leaves RESULTS.md untouched.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { SETS, BENCHMARK_DIR, loadSet, setNote, evaluate, formatText, formatMarkdown } from "./lib.js";

const DEFAULT_SET = "dev";
const RESULTS_FILE = join(BENCHMARK_DIR, "RESULTS.md");
const HEADER = [
  "# Benchmark results",
  "",
  "Generated by `npm run benchmark -- --set=<dev|heldout|heldout2|heldout3|heldout4>` in `backend/engine`.",
  "These are small, synthetic, English-only test sets; the numbers are not a guarantee of real-world",
  "accuracy. dev, heldout and heldout2 were written by the same author with fictional brands and reserved",
  "domains. The dev set was used to tune the rules; the held-out sets were not.",
  "",
  "heldout3 (30 messages, 15 scam / 15 benign) was written by a third party (Gemini). It was not seen",
  "while the round 1 rules were written. **heldout3 is now seen, used for rule tuning in round 2**: its",
  "misses guided lookalike-lure-domain, utility-disconnection-threat, payment-failed-lure,",
  "account-security-lure, the job-fee floor and the remote-work task-job path. Its round 2 numbers below",
  "are therefore optimistic and are not a held-out measure. The rules are general (no sentence from",
  "heldout3 is in a rule or a test). Round 1 result, measured before it was seen: 60.0% detection (9/15),",
  "13.3% strong, 0.0% false alarms. It uses real Bangladeshi service names (bKash, Nagad, DESCO...) and",
  "throwaway defanged domains. Known limitation: 3 romanized-Bengali messages in the draft were replaced",
  "by English versions, so the set does not measure mixed-language messages. h3-s06 (scam: \"my main",
  "number got blocked... urgent 3,000 BDT bKash\") and h3-b13 (benign: \"my card got declined... send me",
  "600 BDT on bKash\") are near-twins that a rule engine cannot reliably separate; h3-s06 is still missed.",
  "",
  "heldout4 is reserved and empty, kept for 30 fresh messages that nobody has seen. Until it is filled",
  "there is no unseen measure of the round 2 rules.",
].join("\n");

function parseSet(argv) {
  const arg = argv.find((a) => a.startsWith("--set="));
  const name = arg ? arg.slice("--set=".length) : DEFAULT_SET;
  if (!SETS.includes(name)) {
    console.error(`Unknown set "${name}". Use --set=${SETS.join("|")}.`);
    process.exit(2);
  }
  return name;
}

function updateResults(name, section) {
  const start = `<!-- set:${name} -->`;
  const end = `<!-- /set:${name} -->`;
  const block = `${start}\n${section}\n${end}`;
  const sections = {};
  if (existsSync(RESULTS_FILE)) {
    const old = readFileSync(RESULTS_FILE, "utf8");
    for (const s of SETS) {
      const m = old.match(new RegExp(`<!-- set:${s} -->[\\s\\S]*?<!-- /set:${s} -->`));
      if (m) sections[s] = m[0];
    }
  }
  sections[name] = block;
  const body = SETS.filter((s) => sections[s]).map((s) => sections[s]).join("\n\n");
  writeFileSync(RESULTS_FILE, `${HEADER}\n\n${body}\n`);
}

const name = parseSet(process.argv.slice(2));
const messages = loadSet(name);
if (messages.length === 0) {
  console.log(`Benchmark set: ${name} is empty, nothing to score.`);
  const note = setNote(name);
  if (note) console.log(note);
  process.exit(0);
}
const ev = evaluate(messages);
console.log(formatText(name, ev));
updateResults(name, formatMarkdown(name, ev, new Date().toISOString().slice(0, 10)));
console.log(`\nWrote ${RESULTS_FILE}`);
